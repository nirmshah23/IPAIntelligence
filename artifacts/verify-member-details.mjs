import { chromium } from '@playwright/test';
const browser = await chromium.launch({channel:'msedge',headless:true});
const page = await browser.newPage();
const errors=[]; page.on('pageerror', e=>errors.push(e.message));
const assert=(ok,message)=>{if(!ok)throw Error(message)};
await page.goto('http://127.0.0.1:4173/#/intelligence/compliance');
await page.getByRole('button',{name:/View \d+ assigned members/}).first().click();
await page.getByRole('heading',{name:'Membership',exact:true}).waitFor();
const provider=await page.getByRole('combobox',{name:/^Assigned PCP/}).inputValue();
await page.getByRole('combobox',{name:'Reporting period',exact:true}).selectOption('2025-Q3');
await page.locator('tbody button:visible').first().click();
await page.getByRole('heading',{name:'Alex Morgan 1',exact:true}).waitFor();
assert(page.url().includes('/member-details?'),'Missing detail route');
assert(await page.getByRole('heading',{name:'Membership',exact:true}).count()===0,'Directory remains visible');
await page.getByRole('heading',{name:'AWV visit history',exact:true}).waitFor();
const dates=await page.locator('time').allTextContents();
assert(dates.length>=3,'AWV history missing');
assert(dates[0]==='2025-07-01','AWV period date incorrect');
assert(await page.locator('dd').filter({hasText:'Cedarbridge Health'}).count()===1,'Health plan name missing');
assert(await page.locator('dt').filter({hasText:/^Product$/}).count()===0,'Product still present');
await page.reload();
await page.getByRole('heading',{name:'Alex Morgan 1',exact:true}).waitFor();
await page.waitForFunction(()=>document.querySelector('time')?.textContent==='2025-07-01');
assert(JSON.stringify(await page.locator('time').allTextContents())===JSON.stringify(dates),'History changed after reload');
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'artifacts/member-details-mobile.png',fullPage:true});
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile overflow');
await page.getByRole('button',{name:'Back to Membership',exact:true}).click();
assert(await page.getByRole('combobox',{name:/^Assigned PCP/}).inputValue()===provider,'PCP filter lost');
await page.getByRole('combobox',{name:/^Health plan line of business/}).selectOption('Medicaid');
await page.getByRole('combobox',{name:/^Health planCedar|^Health planAll/}).count();
await page.getByRole('button',{name:'Reset filters',exact:true}).click();
await page.goto('http://127.0.0.1:4173/#/intelligence/member-details?member=invalid');
await page.getByRole('heading',{name:'Member not found',exact:true}).waitFor();
await page.goto('http://127.0.0.1:4173/#/intelligence/member-details?member=DEMO-IND-0001-0178&period=2026-Q1');
await page.getByText('No AWV visits recorded.',{exact:true}).waitFor();
const response=await page.request.get('http://127.0.0.1:4173/missing-member-route');
assert(response.status()===404,'Missing path should 404');
assert(errors.length===0,JSON.stringify(errors));
console.log(JSON.stringify({provider,dates,reload:true,mobile:true,emptyHistory:true,missingMember:true,missingRoute:response.status(),errors}));
await browser.close();

